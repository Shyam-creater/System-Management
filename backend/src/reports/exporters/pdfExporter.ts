import path from 'path';
import { Response } from 'express';
// @ts-ignore
import pdfMake from 'pdfmake';
import { ReportConfig, QueryResult, ReportFilterValues, UserScope } from '../types.js';

let fontsConfigured = false;

function ensureFonts() {
  if (fontsConfigured) return;
  const basePath = path.resolve(process.cwd(), 'node_modules/pdfmake/fonts/Roboto');
  pdfMake.setFonts({
    Roboto: {
      normal: path.join(basePath, 'Roboto-Regular.ttf'),
      bold: path.join(basePath, 'Roboto-Medium.ttf'),
      italics: path.join(basePath, 'Roboto-Italic.ttf'),
      bolditalics: path.join(basePath, 'Roboto-MediumItalic.ttf')
    }
  });
  fontsConfigured = true;
}

export async function exportToPdf(
  res: Response,
  report: ReportConfig,
  result: QueryResult,
  activeColumnKeys: string[],
  filters: ReportFilterValues,
  scope: UserScope
) {
  ensureFonts();

  const columns = report.columns.filter(c => activeColumnKeys.includes(c.key));
  const isLandscape = columns.length > 6;
  const maxRows = Math.min(5000, result.rows.length);
  const truncated = result.rows.length > 5000;

  // Table header
  const tableHeaders = columns.map(c => ({
    text: c.label,
    style: 'tableHeader',
    alignment: c.type === 'number' || c.type === 'percent' || c.type === 'duration' || c.type === 'size' ? 'right' : 'left'
  }));

  // Table body rows
  const tableBody: any[] = [tableHeaders];

  for (let r = 0; r < maxRows; r++) {
    const rowObj = result.rows[r];
    const rowCells = columns.map(c => {
      let val = rowObj[c.key];
      if (val === undefined || val === null) val = '-';
      if (c.type === 'datetime' && val instanceof Date) {
        val = val.toISOString().replace('T', ' ').substring(0, 16);
      } else if (c.type === 'date' && val instanceof Date) {
        val = val.toISOString().substring(0, 10);
      } else if (c.type === 'percent' && typeof val === 'number') {
        val = `${val.toFixed(1)}%`;
      } else if ((c.type === 'number' || c.type === 'duration' || c.type === 'size') && typeof val === 'number') {
        val = val.toLocaleString();
      }

      const isRight = c.type === 'number' || c.type === 'percent' || c.type === 'duration' || c.type === 'size';
      return {
        text: String(val),
        style: 'tableCell',
        alignment: isRight ? 'right' : 'left',
        fillColor: r % 2 === 1 ? '#f8fafc' : null
      };
    });
    tableBody.push(rowCells);
  }

  // Totals row at the bottom
  if (result.totals && Object.keys(result.totals).length > 0) {
    const totalsCells = columns.map((c, idx) => {
      const val = idx === 0 ? 'Total / Average' : (result.totals[c.key] !== undefined && result.totals[c.key] !== '' ? String(result.totals[c.key]) : '');
      const isRight = c.type === 'number' || c.type === 'percent' || c.type === 'duration' || c.type === 'size';
      return {
        text: val,
        style: 'totalsCell',
        alignment: isRight ? 'right' : 'left',
        fillColor: '#e2e8f0'
      };
    });
    tableBody.push(totalsCells);
  }

  // KPI cards on first page
  const kpiColumns = result.summary.map(kpi => ({
    stack: [
      { text: kpi.label, style: 'kpiLabel' },
      { text: `${kpi.value} ${kpi.unit || ''}`, style: 'kpiValue', color: kpi.color || '#1d68ff' }
    ],
    style: 'kpiBox'
  }));

  const docDefinition: any = {
    pageSize: 'A4',
    pageOrientation: isLandscape ? 'landscape' : 'portrait',
    pageMargins: [30, 45, 30, 40],
    header: (currentPage: number, pageCount: number) => ({
      margin: [30, 15, 30, 10],
      columns: [
        { text: 'ProcessShield Institutional Fleet Guardian', fontSize: 9, color: '#64748b', bold: true },
        { text: report.title, fontSize: 9, alignment: 'right', color: '#1d68ff', bold: true }
      ]
    }),
    footer: (currentPage: number, pageCount: number) => ({
      margin: [30, 10, 30, 15],
      columns: [
        { text: `Generated by ${scope.username} (${scope.role}) on ${new Date().toLocaleString()}`, fontSize: 8, color: '#94a3b8' },
        { text: `Page ${currentPage} of ${pageCount}`, fontSize: 8, alignment: 'right', color: '#94a3b8' }
      ]
    }),
    content: [
      { text: report.title, style: 'reportTitle' },
      { text: report.description, style: 'reportDesc' },

      // Filter metadata box
      {
        style: 'filterBox',
        table: {
          widths: ['*'],
          body: [
            [
              {
                stack: [
                  { text: 'Applied Parameters & Scope', bold: true, fontSize: 10, color: '#1e293b' },
                  { text: `Data Resolution: ${result.resolution.toUpperCase()} | Total Rows: ${result.total.toLocaleString()} | Date Scope: 60-Day Campus History`, fontSize: 8, color: '#475569', margin: [0, 2, 0, 0] }
                ]
              }
            ]
          ]
        },
        layout: {
          fillColor: '#f1f5f9',
          hLineColor: '#cbd5e1',
          vLineColor: '#cbd5e1'
        }
      },

      // KPI summary cards
      kpiColumns.length > 0 ? { columns: kpiColumns, margin: [0, 10, 0, 15] } : {},

      // Main Table
      {
        table: {
          headerRows: 1,
          widths: columns.map(() => '*'),
          body: tableBody
        },
        layout: {
          hLineWidth: () => 0.5,
          vLineWidth: () => 0,
          hLineColor: () => '#e2e8f0'
        }
      },

      // Truncation note if over 5,000 rows
      truncated
        ? {
            text: `Showing 5,000 of ${result.total.toLocaleString()} rows. Use the Excel (.xlsx) export for the complete dataset.`,
            style: 'truncateNote'
          }
        : {}
    ],
    styles: {
      reportTitle: { fontSize: 16, bold: true, color: '#0f172a', margin: [0, 0, 0, 4] },
      reportDesc: { fontSize: 9, color: '#64748b', margin: [0, 0, 0, 10] },
      filterBox: { margin: [0, 0, 0, 10] },
      kpiBox: { margin: [2, 0, 2, 0], padding: 6 },
      kpiLabel: { fontSize: 8, color: '#64748b' },
      kpiValue: { fontSize: 13, bold: true, margin: [0, 2, 0, 0] },
      tableHeader: { fontSize: 8, bold: true, color: '#ffffff', fillColor: '#1d68ff', margin: [2, 4, 2, 4] },
      tableCell: { fontSize: 7.5, color: '#1e293b', margin: [2, 3, 2, 3] },
      totalsCell: { fontSize: 8, bold: true, color: '#0f172a', margin: [2, 4, 2, 4] },
      truncateNote: { fontSize: 9, bold: true, color: '#dc2626', alignment: 'center', margin: [0, 15, 0, 0] }
    }
  };

  const pdfDoc = pdfMake.createPdf(docDefinition);
  const pdfBuffer = await pdfDoc.getBuffer();

  const dateStr = new Date().toISOString().split('T')[0];
  const safeTitle = report.title.replace(/[^a-zA-Z0-9]/g, '_');
  const filename = `ProcessShield_${safeTitle}_${dateStr}.pdf`;

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
  res.setHeader('Content-Length', pdfBuffer.length);

  res.send(pdfBuffer);
}
