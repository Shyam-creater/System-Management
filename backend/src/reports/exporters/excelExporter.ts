import ExcelJS from 'exceljs';
import { Response } from 'express';
import { ReportConfig, QueryResult, ReportFilterValues, UserScope } from '../types.js';

export async function exportToExcel(
  res: Response,
  report: ReportConfig,
  result: QueryResult,
  activeColumnKeys: string[],
  filters: ReportFilterValues,
  scope: UserScope
) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'ProcessShield Fleet Guardian';
  workbook.created = new Date();

  const columns = report.columns.filter(c => activeColumnKeys.includes(c.key));

  // 1. SHEET: SUMMARY
  const summarySheet = workbook.addWorksheet('Summary');
  summarySheet.views = [{ showGridLines: true }];

  summarySheet.addRow(['ProcessShield Fleet Guardian - Institutional Report']);
  summarySheet.getCell('A1').font = { size: 16, bold: true, color: { argb: 'FF1D68FF' } };

  summarySheet.addRow(['Report Title:', report.title]);
  summarySheet.addRow(['Report ID:', report.id]);
  summarySheet.addRow(['Category:', report.category.toUpperCase()]);
  summarySheet.addRow(['Generated By:', `${scope.username} (${scope.role})`]);
  summarySheet.addRow(['Generated At:', new Date().toLocaleString()]);
  summarySheet.addRow(['Total Records:', result.total]);
  summarySheet.addRow(['Data Resolution:', result.resolution]);
  summarySheet.addRow([]);

  summarySheet.addRow(['Key Performance Indicators (KPIs)']);
  summarySheet.getCell('A10').font = { size: 13, bold: true };

  result.summary.forEach((kpi, idx) => {
    summarySheet.addRow([kpi.label, `${kpi.value} ${kpi.unit || ''}`]);
  });

  summarySheet.getColumn('A').width = 28;
  summarySheet.getColumn('B').width = 40;

  // 2. SHEET: DATA
  const dataSheet = workbook.addWorksheet('Data');

  // Freeze top row
  dataSheet.views = [{ state: 'frozen', xSplit: 0, ySplit: 1 }];

  // Setup Header Row
  const headerValues = columns.map(c => c.label);
  const headerRow = dataSheet.addRow(headerValues);
  headerRow.height = 26;

  headerRow.eachCell((cell) => {
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF1D68FF' } // Brand blue #1d68ff
    };
    cell.font = {
      color: { argb: 'FFFFFFFF' },
      bold: true,
      size: 11
    };
    cell.alignment = { vertical: 'middle', horizontal: 'center' };
    cell.border = {
      bottom: { style: 'medium', color: { argb: 'FF0D47A1' } }
    };
  });

  // Enable AutoFilter on header row
  dataSheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: columns.length }
  };

  // Add Data Rows with native data types
  const maxRows = Math.min(100000, result.rows.length);
  for (let r = 0; r < maxRows; r++) {
    const rowObj = result.rows[r];
    const rowVals = columns.map(col => {
      const val = rowObj[col.key];
      if (val === undefined || val === null) return '';
      if (col.type === 'number' || col.type === 'percent' || col.type === 'duration' || col.type === 'size') {
        const num = Number(val);
        return isNaN(num) ? val : num;
      }
      if (col.type === 'datetime' || col.type === 'date') {
        const d = new Date(val);
        return isNaN(d.getTime()) ? val : d;
      }
      return val;
    });

    const dataRow = dataSheet.addRow(rowVals);
    dataRow.height = 20;

    // Apply formatting per cell
    dataRow.eachCell((cell, colNumber) => {
      const colDef = columns[colNumber - 1];
      if (!colDef) return;

      if (colDef.type === 'percent') {
        cell.numFmt = '0.0"%"';
        cell.alignment = { horizontal: 'right' };
        // Conditional colors on utilization
        const numVal = Number(cell.value);
        if (!isNaN(numVal)) {
          if (numVal > 75) {
            cell.font = { color: { argb: 'FFDC2626' }, bold: true }; // Red
          } else if (numVal >= 25) {
            cell.font = { color: { argb: 'FF16A34A' } }; // Green
          } else {
            cell.font = { color: { argb: 'FFD97706' } }; // Amber
          }
        }
      } else if (colDef.type === 'number' || colDef.type === 'duration' || colDef.type === 'size') {
        cell.numFmt = '#,##0.0';
        cell.alignment = { horizontal: 'right' };
      } else if (colDef.type === 'datetime') {
        cell.numFmt = 'yyyy-mm-dd hh:mm';
        cell.alignment = { horizontal: 'center' };
      } else if (colDef.type === 'date') {
        cell.numFmt = 'yyyy-mm-dd';
        cell.alignment = { horizontal: 'center' };
      } else {
        cell.alignment = { horizontal: 'left' };
      }

      // Zebra striping
      if (r % 2 === 1) {
        cell.fill = {
          type: 'pattern',
          pattern: 'solid',
          fgColor: { argb: 'FFF8FAFC' }
        };
      }
    });
  }

  // Add Totals Row using SUBTOTAL formulas
  const totalsRowIndex = maxRows + 2;
  const totalsRowVals = columns.map((col, idx) => {
    if (idx === 0) return 'Total / Average';
    if (!col.total || col.total === 'none') return '';
    const colLetter = dataSheet.getColumn(idx + 1).letter;
    if (col.total === 'sum') {
      return { formula: `SUBTOTAL(9, ${colLetter}2:${colLetter}${totalsRowIndex - 1})` };
    } else if (col.total === 'avg') {
      return { formula: `SUBTOTAL(1, ${colLetter}2:${colLetter}${totalsRowIndex - 1})` };
    }
    return '';
  });

  const totalsRow = dataSheet.addRow(totalsRowVals);
  totalsRow.height = 24;
  totalsRow.eachCell((cell, colNumber) => {
    cell.font = { bold: true, size: 11, color: { argb: 'FF1E293B' } };
    cell.fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FFE2E8F0' }
    };
    cell.border = {
      top: { style: 'thin', color: { argb: 'FF94A3B8' } },
      bottom: { style: 'double', color: { argb: 'FF475569' } }
    };
    const colDef = columns[colNumber - 1];
    if (colDef && colDef.type === 'percent') {
      cell.numFmt = '0.0"%"';
      cell.alignment = { horizontal: 'right' };
    } else if (colDef && (colDef.type === 'number' || colDef.type === 'duration' || colDef.type === 'size')) {
      cell.numFmt = '#,##0.0';
      cell.alignment = { horizontal: 'right' };
    }
  });

  // Fit column widths
  columns.forEach((col, idx) => {
    const colObj = dataSheet.getColumn(idx + 1);
    const headerLen = col.label.length;
    colObj.width = Math.max(headerLen + 4, col.width ? Math.round(col.width / 8) : 15);
  });

  // Send as attachment stream
  const dateStr = new Date().toISOString().split('T')[0];
  const safeTitle = report.title.replace(/[^a-zA-Z0-9]/g, '_');
  const filename = `ProcessShield_${safeTitle}_${dateStr}.xlsx`;

  res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

  await workbook.xlsx.write(res);
  res.end();
}
